/**
 * Builds src/shared/gt1data.ts from a local BOSS TONE STUDIO for GT-1 install.
 *
 * Run with: npx tsx --tsconfig tsconfig.node.json scripts/gen-gt1-data.ts [BTS folder]
 *
 * Two tables come out of it:
 *
 * - where each patch parameter lives in the unit's memory, taken from the
 *   editor's address map and renamed to the parameter names its .tsl files
 *   use, so one name works for the file and for the cable;
 * - a neutral base patch: for every parameter, the value most of the 99 factory
 *   patches agree on. A patch built from a suggestion starts from this rather
 *   than from whatever was in the slot before, so a setting the suggestion
 *   never mentions lands on a sensible default instead of a leftover.
 *
 * The output is committed; this script only needs rerunning if BOSS ships an
 * editor with a different address map.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const BTS = process.argv[2] ?? 'C:/Program Files (x86)/BOSS TONE STUDIO for GT-1'
const map = JSON.parse(readFileSync(join(BTS, '_assets/data/addressmap_gt.json'), 'utf8')) as {
  temporary: Array<{ name?: string; address: string; size?: string }>
}
const presets = JSON.parse(readFileSync(join(BTS, '_assets/data/gt_preset_patches.tsl'), 'utf8')) as {
  patchList: Array<{ params: Record<string, unknown> }>
}

/** The editor's address-map names and its .tsl names differ in a few spellings. */
const SPECIAL: Record<string, string> = {
  'DELAY: PAN TAP TIME': 'delay_tap_time',
  MASTER_CATEGORY2: 'patch_category2',
  PRM_FX2_OVERTONE_DIRECT_MIX: 'prm_fx2_overtone_direct_level'
}

function tslName(name: string): string {
  if (SPECIAL[name]) return SPECIAL[name]
  let s = name
  s = s.replace(/^PRM_CTRL_/, 'CTL_')
  s = s.replace(/^PRM_(?=(NS2|DLY|REVERB)_)/, '')
  s = s.replace('AC.GUITAR SIM', 'ACSIM')
  s = s.replace(/(PS[12]|HR[12]):F#/, '$1:F_S')
  s = s.replace(/(PS[12]|HR[12]):/, '$1')
  s = s.replace(/ \d{3,}$/, '')
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '')
}

const keys = new Set(Object.keys(presets.patchList[0].params))
const addresses: Array<[string, number, number, number]> = []
for (const entry of map.temporary) {
  if (!entry.name || !entry.size) continue
  const key = tslName(entry.name)
  if (!keys.has(key)) throw new Error(`sem par no .tsl: ${entry.name} → ${key}`)
  const [, , page, offset] = entry.address.split(',').map((x) => Number.parseInt(x, 16))
  const size = Number.parseInt(entry.size.split(',')[3], 16)
  addresses.push([key, page, offset, size])
}

const defaults: Record<string, number> = {}
for (const [key] of addresses) {
  const count = new Map<number, number>()
  for (const p of presets.patchList) {
    const v = p.params[key]
    if (typeof v === 'number') count.set(v, (count.get(v) ?? 0) + 1)
  }
  defaults[key] = [...count.entries()].sort((a, b) => b[1] - a[1])[0][0]
}

/*
 * Keys a .tsl carries that are not in the unit's memory map — editor-side
 * labels and bookkeeping. BOSS TONE STUDIO expects them on import, so a file
 * written by the app carries them too, with the factory patches' values.
 */
const addressed = new Set(addresses.map(([k]) => k))
const derived = new Set(addresses.filter(([, , , size]) => size === 2).flatMap(([k]) => [`${k}_h`, `${k}_l`]))
const extras: Record<string, unknown> = {}
for (const key of Object.keys(presets.patchList[0].params)) {
  if (addressed.has(key) || derived.has(key) || key === 'chainParams' || key === 'patchname') continue
  extras[key] = presets.patchList[0].params[key]
}

const out =
  '/*\n' +
  ' * Generated by scripts/gen-gt1-data.ts from BOSS TONE STUDIO for GT-1. Do not edit.\n' +
  ' *\n' +
  ' * GT1_ADDRESSES: [parameter, page, offset, size] inside a patch; the patch base is\n' +
  ' * 60 00 for the temporary patch and 10 nn for user patch Unn+1.\n' +
  ' * GT1_DEFAULTS: for each parameter, the value most factory patches use.\n' +
  ' * GT1_TSL_EXTRAS: .tsl keys the editor keeps for itself, not stored in the unit.\n' +
  ' */\n' +
  `export const GT1_ADDRESSES: ReadonlyArray<readonly [string, number, number, number]> = ${JSON.stringify(addresses)}\n\n` +
  `export const GT1_DEFAULTS: Readonly<Record<string, number>> = ${JSON.stringify(defaults)}\n\n` +
  `export const GT1_TSL_EXTRAS: Readonly<Record<string, unknown>> = ${JSON.stringify(extras)}\n`
writeFileSync(new URL('../src/shared/gt1data.ts', import.meta.url), out)
console.log(`${addresses.length} endereços, ${Object.keys(defaults).length} padrões`)
